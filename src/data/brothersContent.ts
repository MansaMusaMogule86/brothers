export const generateDefaultBiometrics = (ambition: string = 'Perform', level: string = 'Intermediate') => {
  const baseRHR = level === 'Elite Athletic' ? 46 : level === 'Intermediate' ? 52 : 58;
  const baseRec = ambition === 'Recover' || ambition === 'Balance' ? 92 : 88;
  const baseHRV = level === 'Elite Athletic' ? 94 : 76;

  const dates = [
    { date: '16 Oct', day: 'Thu' },
    { date: '17 Oct', day: 'Fri' },
    { date: '18 Oct', day: 'Sat' },
    { date: '19 Oct', day: 'Sun' },
    { date: '20 Oct', day: 'Mon' },
    { date: '21 Oct', day: 'Tue' },
    { date: '22 Oct', day: 'Wed' },
  ];

  const history = dates.map((d, i) => {
    // Trending improvements over time
    const rhr = Math.round(baseRHR + (3 - i * 0.7));
    const rec = Math.min(98, Math.round(baseRec + (i * 1.5) - (i === 2 ? 3 : 0)));
    const hrv = Math.round(baseHRV + (i * 2.2) - (i === 1 ? 2 : 0));
    const sleep = Math.min(97, Math.round(86 + (i * 1.3)));

    return {
      date: d.date,
      dayLabel: d.day,
      restingHeartRate: rhr,
      recoveryEfficiency: rec,
      hrvRmssd: hrv,
      sleepScore: sleep,
      readinessCategory: (rec >= 90 ? 'Optimal' : 'Elevated') as 'Optimal' | 'Elevated',
    };
  });

  const last = history[history.length - 1];
  const first = history[0];

  return {
    biometricSummary: {
      currentRHR: last.restingHeartRate,
      rhrDelta: `${last.restingHeartRate - first.restingHeartRate} bpm (Past 7 Days)`,
      currentRecovery: last.recoveryEfficiency,
      recoveryDelta: `+${last.recoveryEfficiency - first.recoveryEfficiency}% Protocol Adaptive Gain`,
      currentHRV: last.hrvRmssd,
      hrvDelta: `+${last.hrvRmssd - first.hrvRmssd} ms Autonomic Balance`,
      sleepQuality: last.sleepScore,
      overallStatus: 'Optimal Physiological Adaptation' as const,
      lastSynchronized: 'Today, 06:15 GST',
      deviceSource: 'Biometric Telemetry Stream · 30B Street Sanctuary Sync',
    },
    biometricHistory: history,
  };
};
